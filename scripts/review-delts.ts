// Runs the deltoid-head classifier over the whole built-in catalogue and writes docs/delt-heads-review.md
// (every exercise with "shoulders" among the primary muscles: id | name | namePl | result).
//
// Usage: node scripts/review-delts.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { classifyDelts, DELT_LABEL } from '../src/data/deltHeads.ts';

type Raw = {
  id: string;
  name: string;
  namePl?: string;
  equipment: string | null;
  primaryMuscles: string[];
  secondaryMuscles: string[];
};
const read = <T>(f: string): T => JSON.parse(readFileSync(`src/data/${f}`, 'utf8'));

const base = read<Raw[]>('exercise-db.json');
const extra = read<Raw[]>('exercises-extra.json');
const og = read<{ added: Raw[]; polishNames: Record<string, string>; merged: Record<string, string> }>('exercises-og.json');
const withPl = (r: Raw): Raw => (og.polishNames[r.id] ? { ...r, namePl: og.polishNames[r.id] } : r);
const all = [...base.map(withPl), ...extra.filter((e) => !og.merged[e.id]).map(withPl), ...og.added];

const fmt = (d: ReturnType<typeof classifyDelts>): string => {
  if (!d) return '—';
  const list = (hs: (keyof typeof DELT_LABEL)[]) => hs.map((h) => DELT_LABEL[h]).join('+');
  return [d.primary.length ? `primary: ${list(d.primary)}` : '', d.secondary.length ? `secondary: ${list(d.secondary)}` : '']
    .filter(Boolean)
    .join('; ');
};

const rows = all.filter((e) => e.primaryMuscles.includes('shoulders'));
const counts = new Map<string, number>();
const lines = rows.map((e) => {
  const r = fmt(classifyDelts(e));
  counts.set(r, (counts.get(r) ?? 0) + 1);
  return `| ${e.id} | ${e.name} | ${e.namePl ?? ''} | ${r} |`;
});
const summary = [...counts].sort((a, b) => b[1] - a[1]).map(([r, n]) => `- ${r}: ${n}`);

writeFileSync(
  'docs/delt-heads-review.md',
  [
    '# Deltoid heads review',
    '',
    `Generated by \`node scripts/review-delts.ts\`. Exercises with shoulders as a primary muscle: ${rows.length}.`,
    '',
    ...summary,
    '',
    '| id | name | namePl | result |',
    '|---|---|---|---|',
    ...lines,
    '',
  ].join('\n'),
);
console.log(`${rows.length} exercises\n${summary.join('\n')}`);
